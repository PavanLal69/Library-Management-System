export function hasPermission(userRoles: string[], permission: PermissionCode): boolean {
  for (const role of userRoles) {
    const roleKey = role as RoleType;
    const permissionsForRole = ROLE_PERMISSIONS[roleKey];
    if (permissionsForRole && permissionsForRole.includes(permission)) {
      return true;
    }
  }
  return false;
}
